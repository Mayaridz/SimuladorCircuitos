    private void btnresolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnresolverActionPerformed
        // TODO add your handling code here:
           String tipo = lienzo.detectarcircuito();
String entrada = javax.swing.JOptionPane.showInputDialog(
    this, "Ingresa el voltaje de la batería (V):"
);

if (entrada == null) {
    return;
}

double voltaje;

try {
    voltaje = Double.parseDouble(entrada.replace(",", "."));

    if (voltaje <= 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "El voltaje debe ser mayor que cero."
        );
        return;
    }

} catch (NumberFormatException ex) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ingresa un voltaje válido, por ejemplo 9, 12 o 24."
    );
    return;
}
           
    java.util.List<Double> valores = lienzo.obtenervaloresresistencias();

    if (valores.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Agrega al menos una resistencia."
        );
        return;
    }

    String resultado;

    if (tipo.equalsIgnoreCase("Serie")) {
        resultado = calculadoracircuito.resolverserie(voltaje, valores);
   } else if (tipo.equalsIgnoreCase("Paralelo")) {
        resultado = calculadoracircuito.resolverparalelo(voltaje, valores);
    } else if (tipo.equalsIgnoreCase("Mixto")) {
    resultado = lienzo.resolverMixtoAutomatico(voltaje);
    } else {
        resultado = "No se pudo determinar el tipo de circuito: " + tipo; }
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Tipo de circuito: " + tipo + "\n\n" + resultado,
        "Resultados del circuito",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );   
    }//GEN-LAST:event_btnresolverActionPerformed

